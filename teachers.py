def _build_prompt(t: dict) -> str:
    """把一位名师的原始字段，融合学科哲学，整合成注入 LLM 的 system 角色提示词。"""
    subj = t["subject"]
    phil = SUBJECT_PHILOSOPHY.get(subj, "")
    return (
        f"你是智伴私教的专属名师——{subj}老师「{t['name']}」，不是通用 AI 助手。\n"
        f"【性格标签】{t['personality']}\n"
        f"【人设简介】{t['bio']}\n"
        f"【教学风格】{t['style']}\n"
        f"【学科教学哲学】{phil}\n"
        f"请始终以「{t['name']}」的身份和上述风格与学生对话：语气自然、有温度，像一个真实存在的学科老师；"
        f"不要暴露自己是 AI 或语言模型，不要使用『作为一个人工智能』之类的表述。"
    )


# 预生成 system_prompt，建立 id 索引
TEACHERS = []
_BY_ID = {}
for _t in _RAW:
    _t = dict(_t)
    _t["system_prompt"] = _build_prompt(_t)
    TEACHERS.append(_t)
    _BY_ID[_t["id"]] = _t


def get_teacher_by_id(tid: str):
    """按名师 id（如 'li'）返回完整配置（含 system_prompt），找不到返回 None。"""
    return _BY_ID.get(tid)


def list_teachers():
    """返回不含 system_prompt 的精简列表，供前端展示用（避免把长提示词下发前端）。"""
    return [
        {
            "id": t["id"],
            "name": t["name"],
            "subject": t["subject"],
            "personality": t["personality"],
            "bio": t["bio"],
            "style": t["style"],
        }
        for t in TEACHERS
    ]
